-- Track (MVP nov 2026): registro de tiempo propio de BEA.
-- El catálogo (proyectos y actividades) arranca con lo que había en Toggl; los ids de Toggl se conservan.
-- Cada persona registra y edita solo su tiempo; coordinadores y administradores del checador ven a todos.
-- Se puede correr más de una vez. Para quitarlo: drop table track_registros, track_historico, track_actividades, track_etiquetas, track_proyectos;

-- ── 1. Proyectos (los de Toggl + los que se den de alta aquí) ──
create table if not exists track_proyectos (
  id               bigint generated by default as identity (start with 9000000000) primary key,  -- id de Toggl si viene de Toggl
  nombre           text not null,
  clave            text,                                   -- 3 dígitos del nombre (liga con la app)
  cliente          text not null default '',
  activo           boolean not null default true,
  facturable       boolean not null default true,
  horas_estimadas  numeric,
  horas_toggl      numeric not null default 0,             -- acumulado histórico en Toggl al importar
  project_id       uuid references projects(id) on delete set null,
  origen           text not null default 'toggl' check (origen in ('toggl', 'app')),
  created_at       timestamptz not null default now()
);
create index if not exists track_proyectos_clave on track_proyectos(clave);

-- ── 2. Actividades (tareas de Toggl) ─────────────────────────
create table if not exists track_actividades (
  id               bigint generated by default as identity (start with 9000000000) primary key,
  proyecto_id      bigint not null references track_proyectos(id) on delete cascade,
  nombre           text not null,
  activo           boolean not null default true,
  horas_estimadas  numeric,
  horas_toggl      numeric not null default 0,
  origen           text not null default 'toggl' check (origen in ('toggl', 'app')),
  created_at       timestamptz not null default now()
);
create index if not exists track_actividades_proyecto on track_actividades(proyecto_id);

-- ── 3. Etiquetas ─────────────────────────────────────────────
create table if not exists track_etiquetas (
  id      bigint generated by default as identity (start with 9000000000) primary key,
  nombre  text not null unique
);

-- ── 4. Histórico mensual de Toggl (horas por proyecto, persona y mes) ──
create table if not exists track_historico (
  mes          text not null check (mes ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  proyecto_id  bigint not null references track_proyectos(id) on delete cascade,
  email        text not null default '',
  nombre       text not null default '',
  segundos     bigint not null default 0,
  primary key (mes, proyecto_id, email)
);

-- ── 5. Registros de tiempo (lo nuevo, capturado en la app) ───
create table if not exists track_registros (
  id           bigint generated always as identity primary key,
  email        text not null default public.my_email() check (email = lower(email)),
  proyecto_id  bigint not null references track_proyectos(id),
  actividad_id bigint references track_actividades(id) on delete set null,
  concepto_id  uuid references concepts(id) on delete set null,
  descripcion  text not null default '',
  inicio       timestamptz not null default now(),
  fin          timestamptz,                                -- null: el cronómetro sigue corriendo
  facturable   boolean not null default true,
  etiquetas    text[] not null default '{}',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint track_registros_fin_despues check (fin is null or fin > inicio)
);
create index if not exists track_registros_email_inicio on track_registros(email, inicio desc);
create index if not exists track_registros_proyecto on track_registros(proyecto_id);
create unique index if not exists track_registros_un_cronometro on track_registros(email) where fin is null;

-- ── 6. Permisos ──────────────────────────────────────────────
create or replace function public.ve_todo_track()
returns boolean language sql security definer stable set search_path = public as $$
  select public.is_coordinador() or public.es_admin_checador();
$$;

alter table track_proyectos   enable row level security;
alter table track_actividades enable row level security;
alter table track_etiquetas   enable row level security;
alter table track_historico   enable row level security;
alter table track_registros   enable row level security;

drop policy if exists "track_proyectos: autenticados ven" on track_proyectos;
create policy "track_proyectos: autenticados ven" on track_proyectos for select using (auth.uid() is not null);
drop policy if exists "track_proyectos: coordinador edita" on track_proyectos;
create policy "track_proyectos: coordinador edita" on track_proyectos for all using (public.is_coordinador()) with check (public.is_coordinador());

drop policy if exists "track_actividades: autenticados ven" on track_actividades;
create policy "track_actividades: autenticados ven" on track_actividades for select using (auth.uid() is not null);
drop policy if exists "track_actividades: autenticados agregan" on track_actividades;
create policy "track_actividades: autenticados agregan" on track_actividades for insert with check (auth.uid() is not null and origen = 'app');
drop policy if exists "track_actividades: coordinador edita" on track_actividades;
create policy "track_actividades: coordinador edita" on track_actividades for all using (public.is_coordinador()) with check (public.is_coordinador());

drop policy if exists "track_etiquetas: autenticados ven" on track_etiquetas;
create policy "track_etiquetas: autenticados ven" on track_etiquetas for select using (auth.uid() is not null);
drop policy if exists "track_etiquetas: coordinador edita" on track_etiquetas;
create policy "track_etiquetas: coordinador edita" on track_etiquetas for all using (public.is_coordinador()) with check (public.is_coordinador());

drop policy if exists "track_historico: lo suyo o todo" on track_historico;
create policy "track_historico: lo suyo o todo" on track_historico for select
  using (auth.uid() is not null and (email = public.my_email() or public.ve_todo_track()));
drop policy if exists "track_historico: coordinador edita" on track_historico;
create policy "track_historico: coordinador edita" on track_historico for all using (public.is_coordinador()) with check (public.is_coordinador());

drop policy if exists "track_registros: ver lo suyo o todo" on track_registros;
create policy "track_registros: ver lo suyo o todo" on track_registros for select
  using (auth.uid() is not null and (email = public.my_email() or public.ve_todo_track()));
drop policy if exists "track_registros: capturar lo suyo" on track_registros;
create policy "track_registros: capturar lo suyo" on track_registros for insert
  with check (auth.uid() is not null and email = public.my_email());
drop policy if exists "track_registros: editar lo suyo" on track_registros;
create policy "track_registros: editar lo suyo" on track_registros for update
  using (email = public.my_email() or public.is_coordinador()) with check (email = public.my_email() or public.is_coordinador());
drop policy if exists "track_registros: borrar lo suyo" on track_registros;
create policy "track_registros: borrar lo suyo" on track_registros for delete
  using (email = public.my_email() or public.is_coordinador());
